"""Aegisub (.ass) subtitle exporter with optional template preservation."""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path
import re

from transapp.core.models import SubtitleEvent
from transapp.exporters.sanitize import (
    clamp_non_overlapping_intervals,
    ms_to_ass_cs_half_up,
    prepare_export_cues,
    sanitize_ass_dialogue_text,
    snap_ass_centiseconds,
    write_text_atomic,
)

_EVENTS_FORMAT = "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
_STYLES_FORMAT = (
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
    "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, "
    "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
    "Alignment, MarginL, MarginR, MarginV, Encoding"
)
_TRAILING_SECTIONS = frozenset({"[fonts]", "[graphics]", "[aegisub extradata]"})
_UUENCODED_SECTIONS = frozenset({"[fonts]", "[graphics]"})
_KNOWN_ASS_SECTIONS = frozenset(
    {
        "[script info]",
        "[v4+ styles]",
        "[v4 styles]",
        "[events]",
        "[fonts]",
        "[graphics]",
        "[aegisub project garbage]",
        "[aegisub extradata]",
    }
)
_SECTION_HEADER_RE = re.compile(r"\[[A-Za-z0-9 _+\-]+\]")
_UNSAFE_STYLE_CHARS_RE = re.compile(r"[,\r\n]+")


def _format_ass_cs(total_cs: int) -> str:
    clamped_cs = max(0, int(total_cs))
    cs = clamped_cs % 100
    total_s = clamped_cs // 100
    s = total_s % 60
    total_m = total_s // 60
    m = total_m % 60
    h = total_m // 60
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def format_ass_time(ms: int) -> str:
    """Format milliseconds into ASS timestamp ``H:MM:SS.cc`` clamped to >= 0."""
    return _format_ass_cs(ms_to_ass_cs_half_up(ms))


def _build_default_style_line(video_height: int) -> str:
    res_y = max(1, int(video_height))
    font_size = max(16, round(res_y * 0.055))
    margin_v = max(10, round(res_y * 0.04))
    return (
        f"Style: Default,Microsoft YaHei,{font_size},&H00FFFFFF,&H000000FF,"
        f"&H00000000,&H80000000,-1,0,0,0,100,100,0,0,1,2,1,2,20,20,{margin_v},1"
    )


def _build_default_styles_section(video_height: int) -> list[str]:
    return [
        "[V4+ Styles]",
        _STYLES_FORMAT,
        _build_default_style_line(video_height),
    ]


def _build_default_header(video_width: int, video_height: int) -> list[str]:
    res_x = max(1, int(video_width))
    res_y = max(1, int(video_height))
    return [
        "[Script Info]",
        "; Script generated by TransApp",
        "Title: TransApp Export",
        "ScriptType: v4.00+",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: None",
        f"PlayResX: {res_x}",
        f"PlayResY: {res_y}",
        "",
        *_build_default_styles_section(res_y),
    ]


def _is_section_header(line: str) -> bool:
    return _SECTION_HEADER_RE.fullmatch(line.strip()) is not None


def _starts_new_section(line: str, current_key: str | None) -> bool:
    stripped = line.strip()
    if not _is_section_header(stripped):
        return False
    if current_key in _UUENCODED_SECTIONS:
        lower = stripped.lower()
        if lower in _KNOWN_ASS_SECTIONS:
            return True
        return any(("a" <= ch <= "z") or ch == " " for ch in stripped)
    return True


def _extract_styles_from_lines(lines: Sequence[str]) -> tuple[bool, list[str]]:
    has_styles_section = False
    styles: list[str] = []
    seen: set[str] = set()
    in_styles = False
    for line in lines:
        stripped = line.strip()
        if _is_section_header(stripped):
            in_styles = stripped.lower() == "[v4+ styles]"
            if in_styles:
                has_styles_section = True
            continue
        if in_styles and stripped.lower().startswith("style:"):
            candidate = stripped.split(":", 1)[1].split(",", 1)[0].strip()
            if candidate and candidate not in seen:
                seen.add(candidate)
                styles.append(candidate)
    return has_styles_section, styles


def _read_template_text(path: Path) -> str:
    """Decode ASS template with UTF-16 LE/BE BOM detection before falling back to UTF-8."""
    raw_bytes = Path(path).read_bytes()
    if raw_bytes.startswith((b"\xff\xfe", b"\xfe\xff")):
        return raw_bytes.decode("utf-16")
    return raw_bytes.decode("utf-8-sig")


def _sanitize_style_name(style_name: str | None, fallback: str) -> str:
    """Strip ASS field/line separators from style_name, falling back when empty."""
    safe_fallback = _UNSAFE_STYLE_CHARS_RE.sub("", fallback).strip() or "Default"
    if not style_name:
        return safe_fallback
    cleaned = _UNSAFE_STYLE_CHARS_RE.sub("", style_name).strip()
    return cleaned or safe_fallback


def list_ass_template_styles(template_path: Path) -> list[str]:
    """Return deduplicated style names declared under ``[V4+ Styles]`` in file order."""
    raw = _read_template_text(Path(template_path))
    lines = raw.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    _, styles = _extract_styles_from_lines(lines)
    return styles


def _parse_positive_int(raw_value: str) -> int | None:
    try:
        val = int(raw_value.strip())
    except ValueError:
        return None
    return val if val > 0 else None


def _ensure_script_info_playres(
    lines: list[str],
    res_x: int,
    res_y: int,
) -> tuple[list[str], int]:
    """Preserve valid template PlayResX/Y (> 0), injecting fallback values only when missing or <= 0."""
    result = list(lines)
    script_info_idx: int | None = None
    for idx, line in enumerate(result):
        if line.strip().lower() == "[script info]":
            script_info_idx = idx
            break

    if script_info_idx is None:
        header = [
            "[Script Info]",
            "ScriptType: v4.00+",
            f"PlayResX: {res_x}",
            f"PlayResY: {res_y}",
        ]
        if result:
            return [*header, "", *result], res_y
        return header, res_y

    section_end = len(result)
    for idx in range(script_info_idx + 1, len(result)):
        if _is_section_header(result[idx]):
            section_end = idx
            break

    has_res_x = False
    has_res_y = False
    effective_res_y = res_y
    last_content_idx = script_info_idx

    for idx in range(script_info_idx + 1, section_end):
        stripped = result[idx].strip()
        if stripped:
            last_content_idx = idx
        lower = stripped.lower()
        if lower.startswith("playresx:"):
            parsed = _parse_positive_int(stripped.split(":", 1)[1])
            if parsed is None:
                result[idx] = f"PlayResX: {res_x}"
            has_res_x = True
        elif lower.startswith("playresy:"):
            parsed = _parse_positive_int(stripped.split(":", 1)[1])
            if parsed is None:
                result[idx] = f"PlayResY: {res_y}"
                effective_res_y = res_y
            else:
                effective_res_y = parsed
            has_res_y = True

    insertions: list[str] = []
    if not has_res_x:
        insertions.append(f"PlayResX: {res_x}")
    if not has_res_y:
        insertions.append(f"PlayResY: {res_y}")

    if insertions:
        insert_pos = last_content_idx + 1
        result[insert_pos:insert_pos] = insertions

    return result, effective_res_y


def _trim_blank_edges(lines: Sequence[str]) -> list[str]:
    result = list(lines)
    while result and not result[0].strip():
        result.pop(0)
    while result and not result[-1].strip():
        result.pop()
    return result


def _split_ini_sections(
    lines: Sequence[str],
) -> tuple[list[str], list[tuple[str, list[str]]]]:
    """Split ASS script lines into leading preamble and ordered ``(lower_header, block)`` pairs."""
    preamble: list[str] = []
    sections: list[tuple[str, list[str]]] = []
    current_key: str | None = None
    current_block: list[str] = []

    for line in lines:
        if _starts_new_section(line, current_key):
            if current_key is not None:
                sections.append((current_key, _trim_blank_edges(current_block)))
            current_key = line.strip().lower()
            current_block = [line.strip()]
        elif current_key is None:
            preamble.append(line)
        else:
            current_block.append(line)

    if current_key is not None:
        sections.append((current_key, _trim_blank_edges(current_block)))

    return _trim_blank_edges(preamble), sections


def _join_section_blocks(blocks: Sequence[Sequence[str]]) -> list[str]:
    joined: list[str] = []
    for block in blocks:
        trimmed = _trim_blank_edges(block)
        if not trimmed:
            continue
        if joined:
            joined.append("")
        joined.extend(trimmed)
    return joined


def _parse_ass_template(
    template_path: Path,
    res_x: int,
    res_y: int,
) -> tuple[list[str], list[str], str]:
    raw = _read_template_text(Path(template_path))
    lines = raw.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    preamble, sections = _split_ini_sections(lines)

    script_info_block: list[str] | None = None
    garbage_blocks: list[list[str]] = []
    styles_block: list[str] | None = None
    other_header_blocks: list[list[str]] = []
    trailing_blocks: list[list[str]] = []

    for sec_key, block in sections:
        if sec_key == "[events]":
            continue
        if sec_key == "[script info]":
            if script_info_block is None:
                script_info_block = list(block)
            else:
                script_info_block.extend(block[1:])
        elif sec_key == "[aegisub project garbage]":
            garbage_blocks.append(list(block))
        elif sec_key == "[v4+ styles]":
            if styles_block is None:
                styles_block = list(block)
            else:
                has_format = any(
                    ln.strip().lower().startswith("format:") for ln in styles_block[1:]
                )
                for ln in block[1:]:
                    if has_format and ln.strip().lower().startswith("format:"):
                        continue
                    styles_block.append(ln)
        elif sec_key in _TRAILING_SECTIONS:
            trailing_blocks.append(list(block))
        else:
            other_header_blocks.append(list(block))

    script_info_seed = script_info_block if script_info_block is not None else preamble
    script_info_lines, effective_res_y = _ensure_script_info_playres(
        script_info_seed, res_x, res_y
    )

    if styles_block is None:
        styles_block = _build_default_styles_section(effective_res_y)
        styles = ["Default"]
    else:
        _, styles = _extract_styles_from_lines(styles_block)
        if not styles:
            has_format = any(
                ln.strip().lower().startswith("format:") for ln in styles_block[1:]
            )
            if not has_format:
                styles_block.append(_STYLES_FORMAT)
            styles_block.append(_build_default_style_line(effective_res_y))
            styles = ["Default"]

    header_blocks: list[list[str]] = [
        script_info_lines,
        *garbage_blocks,
        styles_block,
        *other_header_blocks,
    ]
    header_lines = _join_section_blocks(header_blocks)
    suffix_lines = _join_section_blocks(trailing_blocks)

    default_style = styles[0] if styles else "Default"
    return header_lines, suffix_lines, default_style


def export_ass(
    events: Sequence[SubtitleEvent],
    output_path: Path,
    video_width: int = 1920,
    video_height: int = 1080,
    template_path: Path | None = None,
    *,
    width: int | None = None,
    height: int | None = None,
    style_name: str | None = None,
    frame_pts_ms: Sequence[int] | None = None,
) -> Path:
    """Export subtitle events as a UTF-8 Aegisub ``.ass`` script."""
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)

    res_x = max(1, int(width if width is not None else video_width))
    res_y = max(1, int(height if height is not None else video_height))

    if template_path is not None:
        header_lines, suffix_lines, default_style = _parse_ass_template(
            Path(template_path), res_x, res_y
        )
    else:
        header_lines = _build_default_header(res_x, res_y)
        suffix_lines = []
        default_style = "Default"

    chosen_style = _sanitize_style_name(style_name, default_style)

    output_lines = list(header_lines)
    if output_lines:
        output_lines.append("")
    output_lines.append("[Events]")
    output_lines.append(_EVENTS_FORMAT)

    cues = prepare_export_cues(events)
    raw_timings = [
        snap_ass_centiseconds(ev.start_ms, ev.end_ms, frame_pts_ms) for ev in cues
    ]
    resolved_timings = clamp_non_overlapping_intervals(raw_timings)

    for event, (start_cs, end_cs) in zip(cues, resolved_timings):
        actor = f"CHECK_{event.confidence:.2f}" if event.flagged else ""
        clean_text = sanitize_ass_dialogue_text(event.text)
        output_lines.append(
            f"Dialogue: 0,{_format_ass_cs(start_cs)},{_format_ass_cs(end_cs)},"
            f"{chosen_style},{actor},0,0,0,,{clean_text}"
        )

    if suffix_lines:
        output_lines.append("")
        output_lines.extend(suffix_lines)

    write_text_atomic(out, "\n".join(output_lines) + "\n", encoding="utf-8", newline="\n")
    return out
