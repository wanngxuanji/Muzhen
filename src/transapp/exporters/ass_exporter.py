"""Aegisub (.ass) subtitle exporter with optional template preservation."""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from transapp.core.models import SubtitleEvent
from transapp.exporters.sanitize import (
    clamp_non_overlapping_intervals,
    ms_to_ass_cs_half_up,
    prepare_export_cues,
    sanitize_ass_dialogue_text,
    snap_ass_centiseconds,
)

_EVENTS_FORMAT = "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
_STYLES_FORMAT = (
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
    "OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, "
    "ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
    "Alignment, MarginL, MarginR, MarginV, Encoding"
)


def _format_ass_cs(total_cs: int) -> str:
    clamped_cs = max(0, int(total_cs))
    cs = clamped_cs % 100
    total_s = clamped_cs // 100
    s = total_s % 60
    total_m = total_s // 60
    m = total_m % 60
    h = total_m // 60
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def format_ass_time(ms: int) -> str:
    """Format milliseconds into ASS timestamp ``H:MM:SS.cc`` clamped to >= 0."""
    return _format_ass_cs(ms_to_ass_cs_half_up(ms))


def _build_default_styles_section(video_height: int) -> list[str]:
    res_y = max(1, int(video_height))
    font_size = max(16, round(res_y * 0.055))
    margin_v = max(10, round(res_y * 0.04))
    return [
        "[V4+ Styles]",
        _STYLES_FORMAT,
        (
            f"Style: Default,Microsoft YaHei,{font_size},&H00FFFFFF,&H000000FF,"
            f"&H00000000,&H80000000,-1,0,0,0,100,100,0,0,1,2,1,2,20,20,{margin_v},1"
        ),
    ]


def _build_default_header(video_width: int, video_height: int) -> list[str]:
    res_x = max(1, int(video_width))
    res_y = max(1, int(video_height))
    return [
        "[Script Info]",
        "; Script generated by TransApp",
        "Title: TransApp Export",
        "ScriptType: v4.00+",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: None",
        f"PlayResX: {res_x}",
        f"PlayResY: {res_y}",
        "",
        *_build_default_styles_section(res_y),
    ]


def _is_section_header(line: str) -> bool:
    stripped = line.strip()
    return len(stripped) >= 3 and stripped.startswith("[") and stripped.endswith("]")


def _extract_styles_from_lines(lines: Sequence[str]) -> tuple[bool, list[str]]:
    has_styles_section = False
    styles: list[str] = []
    seen: set[str] = set()
    in_styles = False
    for line in lines:
        stripped = line.strip()
        if _is_section_header(stripped):
            in_styles = stripped.lower() == "[v4+ styles]"
            if in_styles:
                has_styles_section = True
            continue
        if in_styles and stripped.lower().startswith("style:"):
            candidate = stripped.split(":", 1)[1].split(",", 1)[0].strip()
            if candidate and candidate not in seen:
                seen.add(candidate)
                styles.append(candidate)
    return has_styles_section, styles


def list_ass_template_styles(template_path: Path) -> list[str]:
    """Return deduplicated style names declared under ``[V4+ Styles]`` in file order."""
    raw = Path(template_path).read_text(encoding="utf-8-sig")
    lines = raw.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    _, styles = _extract_styles_from_lines(lines)
    return styles


def _parse_positive_int(raw_value: str) -> int | None:
    try:
        val = int(raw_value.strip())
    except ValueError:
        return None
    return val if val > 0 else None


def _ensure_script_info_playres(
    lines: list[str],
    res_x: int,
    res_y: int,
) -> tuple[list[str], int]:
    """Preserve valid template PlayResX/Y (> 0), injecting fallback values only when missing or <= 0."""
    result = list(lines)
    script_info_idx: int | None = None
    for idx, line in enumerate(result):
        if line.strip().lower() == "[script info]":
            script_info_idx = idx
            break

    if script_info_idx is None:
        header = [
            "[Script Info]",
            "ScriptType: v4.00+",
            f"PlayResX: {res_x}",
            f"PlayResY: {res_y}",
        ]
        if result:
            return [*header, "", *result], res_y
        return header, res_y

    section_end = len(result)
    for idx in range(script_info_idx + 1, len(result)):
        if _is_section_header(result[idx]):
            section_end = idx
            break

    has_res_x = False
    has_res_y = False
    effective_res_y = res_y
    last_content_idx = script_info_idx

    for idx in range(script_info_idx + 1, section_end):
        stripped = result[idx].strip()
        if stripped:
            last_content_idx = idx
        lower = stripped.lower()
        if lower.startswith("playresx:"):
            parsed = _parse_positive_int(stripped.split(":", 1)[1])
            if parsed is None:
                result[idx] = f"PlayResX: {res_x}"
            has_res_x = True
        elif lower.startswith("playresy:"):
            parsed = _parse_positive_int(stripped.split(":", 1)[1])
            if parsed is None:
                result[idx] = f"PlayResY: {res_y}"
                effective_res_y = res_y
            else:
                effective_res_y = parsed
            has_res_y = True

    insertions: list[str] = []
    if not has_res_x:
        insertions.append(f"PlayResX: {res_x}")
    if not has_res_y:
        insertions.append(f"PlayResY: {res_y}")

    if insertions:
        insert_pos = last_content_idx + 1
        result[insert_pos:insert_pos] = insertions

    return result, effective_res_y


def _parse_ass_template(
    template_path: Path,
    res_x: int,
    res_y: int,
) -> tuple[list[str], list[str], str]:
    raw = Path(template_path).read_text(encoding="utf-8-sig")
    lines = raw.replace("\r\n", "\n").replace("\r", "\n").split("\n")

    events_idx: int | None = None
    for idx, line in enumerate(lines):
        if line.strip().lower() == "[events]":
            events_idx = idx
            break

    if events_idx is None:
        prefix_lines = list(lines)
        suffix_lines: list[str] = []
    else:
        prefix_lines = lines[:events_idx]
        next_section_idx: int | None = None
        for idx in range(events_idx + 1, len(lines)):
            if _is_section_header(lines[idx]):
                next_section_idx = idx
                break
        suffix_lines = lines[next_section_idx:] if next_section_idx is not None else []

    while prefix_lines and prefix_lines[-1] == "":
        prefix_lines.pop()
    while suffix_lines and suffix_lines[-1] == "":
        suffix_lines.pop()

    prefix_lines, effective_res_y = _ensure_script_info_playres(prefix_lines, res_x, res_y)
    has_styles_section, styles = _extract_styles_from_lines(prefix_lines)
    if not has_styles_section:
        if prefix_lines:
            prefix_lines.append("")
        prefix_lines.extend(_build_default_styles_section(effective_res_y))

    default_style = styles[0] if styles else "Default"
    return prefix_lines, suffix_lines, default_style


def export_ass(
    events: Sequence[SubtitleEvent],
    output_path: Path,
    video_width: int = 1920,
    video_height: int = 1080,
    template_path: Path | None = None,
    *,
    width: int | None = None,
    height: int | None = None,
    style_name: str | None = None,
    frame_pts_ms: Sequence[int] | None = None,
) -> Path:
    """Export subtitle events as a UTF-8 Aegisub ``.ass`` script."""
    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)

    res_x = max(1, int(width if width is not None else video_width))
    res_y = max(1, int(height if height is not None else video_height))

    if template_path is not None:
        header_lines, suffix_lines, default_style = _parse_ass_template(
            Path(template_path), res_x, res_y
        )
    else:
        header_lines = _build_default_header(res_x, res_y)
        suffix_lines = []
        default_style = "Default"

    chosen_style = style_name.strip() if (style_name and style_name.strip()) else default_style

    output_lines = list(header_lines)
    if output_lines:
        output_lines.append("")
    output_lines.append("[Events]")
    output_lines.append(_EVENTS_FORMAT)

    cues = prepare_export_cues(events)
    raw_timings = [
        snap_ass_centiseconds(ev.start_ms, ev.end_ms, frame_pts_ms) for ev in cues
    ]
    resolved_timings = clamp_non_overlapping_intervals(raw_timings)

    for event, (start_cs, end_cs) in zip(cues, resolved_timings):
        actor = f"CHECK_{event.confidence:.2f}" if event.flagged else ""
        clean_text = sanitize_ass_dialogue_text(event.text)
        output_lines.append(
            f"Dialogue: 0,{_format_ass_cs(start_cs)},{_format_ass_cs(end_cs)},"
            f"{chosen_style},{actor},0,0,0,,{clean_text}"
        )

    if suffix_lines:
        output_lines.append("")
        output_lines.extend(suffix_lines)

    with out.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(output_lines) + "\n")
    return out
