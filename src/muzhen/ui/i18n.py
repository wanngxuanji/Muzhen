def detect_system_language(locale_name: str | None = None) -> str:
    """Resolve the active UI language from an OS/Qt locale identifier."""
    raw = locale_name
    if raw is None:
        try:
            qt_name = QLocale.system().name()
        except Exception:
            qt_name = ""
        if isinstance(qt_name, str) and qt_name.strip() and qt_name.strip().upper() not in ("C", "POSIX"):
            raw = qt_name
        else:
            raw = locale.getlocale()[0] or "en"
    normalized = str(raw).strip().lower().replace("-", "_")
    if normalized.startswith("vi"):
        return "vi"
    if normalized.startswith("zh"):
        return "zh"
    return "en"


def resolve_language(preference: str | None, locale_name: str | None = None) -> str:
    """Resolve a stored language preference (or ``'auto'``) to a supported language code."""
    if isinstance(preference, str):
        normalized = preference.strip().lower()
        if normalized in SUPPORTED_LANGUAGES:
            return normalized
    return detect_system_language(locale_name)


def tr(lang: str, key: str, **kwargs: Any) -> str:
    """Look up a localized UI string with English fallback and optional formatting."""
    lang_code = lang.strip().lower() if isinstance(lang, str) else "en"
    table = TRANSLATIONS.get(lang_code, TRANSLATIONS["en"])
    template = table.get(key)
    if template is None:
        template = TRANSLATIONS["en"].get(key, key)
    if kwargs:
        return template.format(**kwargs)
    return template
